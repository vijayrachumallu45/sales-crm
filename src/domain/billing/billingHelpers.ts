import { BillingConfig, BillingRule } from './billingSchema';

export class BillingDomainHelper {
  public static validateRecord<T extends { id: string }>(record: T, rules: BillingRule[]): { valid: boolean; errors: string[] } {
    const errors: string[] = [];
    for (const rule of rules) {
      if (rule.active && !record.id) {
        errors.push(rule.errorMessage);
      }
    }
    return { valid: errors.length === 0, errors };
  }

  public static calculateBillingMetric(values: number[]): { sum: number; avg: number; min: number; max: number } {
    if (!values || values.length === 0) return { sum: 0, avg: 0, min: 0, max: 0 };
    const sum = values.reduce((a, b) => a + b, 0);
    const avg = sum / values.length;
    const min = Math.min(...values);
    const max = Math.max(...values);
    return { sum, avg, min, max };
  }

  public static formatBillingCode(prefix: string, index: number): string {
    return `${prefix.toUpperCase()}-${String(index).padStart(6, '0')}`;
  }
}

