export interface BillingConfig {
  id: string;
  name: string;
  enabled: boolean;
  version: string;
  description: string;
  maxRecords: number;
  retryAttempts: number;
  timeoutMs: number;
  auditEnabled: boolean;
}

export interface BillingRule {
  id: string;
  code: string;
  name: string;
  category: 'billing_validation' | 'billing_automation' | 'billing_compliance';
  expression: string;
  errorMessage: string;
  severity: 'low' | 'medium' | 'high' | 'critical';
  active: boolean;
}

export interface BillingTaxonomy {
  categoryCode: string;
  displayName: string;
  subCategories: string[];
  tags: string[];
  metadata: Record<string, string | number | boolean>;
}

