export interface CommissionsConfig {
  id: string;
  name: string;
  enabled: boolean;
  version: string;
  description: string;
  maxRecords: number;
  retryAttempts: number;
  timeoutMs: number;
  auditEnabled: boolean;
}

export interface CommissionsRule {
  id: string;
  code: string;
  name: string;
  category: 'commissions_validation' | 'commissions_automation' | 'commissions_compliance';
  expression: string;
  errorMessage: string;
  severity: 'low' | 'medium' | 'high' | 'critical';
  active: boolean;
}

export interface CommissionsTaxonomy {
  categoryCode: string;
  displayName: string;
  subCategories: string[];
  tags: string[];
  metadata: Record<string, string | number | boolean>;
}

