/**
 * INVENTORY Domain Schemas and Rules Definitions
 * Enterprise Sales CRM inventory domain model specifications
 */

export interface InventoryConfig {
  id: string;
  name: string;
  enabled: boolean;
  version: string;
  description: string;
  maxRecords: number;
  retryAttempts: number;
  timeoutMs: number;
  auditEnabled: boolean;
}

export interface InventoryRule {
  id: string;
  code: string;
  name: string;
  category: 'inventory_validation' | 'inventory_automation' | 'inventory_compliance';
  expression: string;
  errorMessage: string;
  severity: 'low' | 'medium' | 'high' | 'critical';
  active: boolean;
}

export interface InventoryTaxonomy {
  categoryCode: string;
  displayName: string;
  subCategories: string[];
  tags: string[];
  metadata: Record<string, string | number | boolean>;
}

