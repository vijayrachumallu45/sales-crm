export interface ComplianceConfig {
  id: string;
  name: string;
  enabled: boolean;
  version: string;
  description: string;
  maxRecords: number;
  retryAttempts: number;
  timeoutMs: number;
  auditEnabled: boolean;
}

export interface ComplianceRule {
  id: string;
  code: string;
  name: string;
  category: 'compliance_validation' | 'compliance_automation' | 'compliance_compliance';
  expression: string;
  errorMessage: string;
  severity: 'low' | 'medium' | 'high' | 'critical';
  active: boolean;
}

export interface ComplianceTaxonomy {
  categoryCode: string;
  displayName: string;
  subCategories: string[];
  tags: string[];
  metadata: Record<string, string | number | boolean>;
}

